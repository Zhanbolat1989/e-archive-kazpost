"""Электронные копии документов (ТС-176 п. 11.6–11.7).

Скан бумажного документа — электронная копия, а не электронный документ: ЭЦП
автора у него нет. Копии учитываются отдельной описью; после сверки с бумажным
подлинником работник архива удостоверяет копию собственной ЭЦП. Если подлинника
нет или сверка отрицательная, копия уничтожается по акту, утверждённому
руководителем по согласованию с ЦЭК (ЭК).

Здесь только правила переходов между состояниями — они проверяются тестами
без базы данных.
"""
PENDING = "pending"
CERTIFIED = "certified"
MISMATCH = "mismatch"
NO_ORIGINAL = "no_original"

STATUSES = {
    PENDING: "Сверка с подлинником не проводилась",
    CERTIFIED: "Сверена с подлинником, удостоверена ЭЦП",
    MISMATCH: "Отрицательный результат сверки",
    NO_ORIGINAL: "Подлинник отсутствует",
}

# Копии, подлежащие уничтожению по акту (п. 11.7).
DESTROYABLE = (MISMATCH, NO_ORIGINAL)

# Вид акта и префикс номера: акты об уничтожении копий нумеруются отдельно от
# актов о выделении к уничтожению по истечении срока хранения.
ACT_KIND = "ecopy"
ACT_PREFIX = "АУК"


def check_certify(status: str) -> None:
    """Удостоверить ЭЦП можно только копию, сверка которой ещё не проводилась:
    отрицательный результат сверки подписью не перекрывается."""
    if status != PENDING:
        raise ValueError(
            f"Удостоверить можно только копию со статусом «{STATUSES[PENDING]}»"
        )


def check_reconcile(status: str, result: str) -> None:
    """Отрицательный результат сверки: подлинника нет либо копия с ним не совпала.

    Удостоверенную копию так не переоценить: её подпись — юридически значимый
    факт, и отменяться он должен явной процедурой, а не одним нажатием."""
    if result not in DESTROYABLE:
        raise ValueError("Результат сверки: " + ", ".join(DESTROYABLE))
    if status not in (PENDING, *DESTROYABLE):
        raise ValueError(
            f"Копия в статусе «{STATUSES.get(status, status or 'не копия')}» "
            "повторной сверке не подлежит"
        )


def check_unmark(status: str) -> None:
    """Снять отметку «электронная копия» нельзя у удостоверенной копии."""
    if status == CERTIFIED:
        raise ValueError("Копия удостоверена ЭЦП — отметку снять нельзя")


def check_destroyable(status: str) -> None:
    if status not in DESTROYABLE:
        raise ValueError(
            "В акт об уничтожении копий включаются только копии без подлинника "
            "или с отрицательным результатом сверки"
        )

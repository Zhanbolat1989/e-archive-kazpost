def _req(method, path, token=None, data=None, form=None, multipart=None):
    url = API + path
    headers = {}
    body = None
    if token:
        headers["Authorization"] = "Bearer " + token
    if form is not None:
        body = "&".join(f"{k}={urllib.parse.quote(str(v))}" for k, v in form.items()).encode()
        headers["Content-Type"] = "application/x-www-form-urlencoded"
    elif multipart is not None:
        boundary = "----earchiveseed7913"
        buf = io.BytesIO()
        for k, v in multipart["fields"].items():
            buf.write(f"--{boundary}\r\n".encode())
            buf.write(f'Content-Disposition: form-data; name="{k}"\r\n\r\n'.encode("utf-8"))
            buf.write(str(v).encode("utf-8"))
            buf.write(b"\r\n")
        fn = multipart["filename"]
        buf.write(f"--{boundary}\r\n".encode())
        buf.write(f'Content-Disposition: form-data; name="file"; filename="{fn}"\r\n'.encode("utf-8"))
        buf.write(b"Content-Type: text/plain\r\n\r\n")
        buf.write(multipart["content"].encode("utf-8"))
        buf.write(f"\r\n--{boundary}--\r\n".encode())
        body = buf.getvalue()
        headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
    elif data is not None:
        body = json.dumps(data).encode("utf-8")
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=body, headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


